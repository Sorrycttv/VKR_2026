def _extra_ingredients(name: str, slot: str) -> dict[str, int]:
    """Keep the expanded demo catalogue consistent enough for pantry matching."""

    title = name.casefold()
    if slot == "breakfast":
        if any(word in title for word in ("омлет", "яичница", "шакшука", "сэндвич")):
            return {"Яйца": 120, "Томаты": 120, "Хлеб цельнозерновой": 70, "Овощи": 120}
        if any(word in title for word in ("творож", "сырники", "вафли")):
            return {"Творог": 200, "Яйца": 60, "Мука": 50, "Ягоды": 80}
        if "тост" in title or "бутерброд" in title:
            return {"Хлеб цельнозерновой": 100, "Авокадо": 80, "Яйца": 60, "Овощи": 100}
        return {"Крупа": 80, "Молоко": 220, "Банан": 120, "Ягоды": 80}
    if slot == "snack":
        if any(word in title for word in ("йогурт", "творог", "сыр")):
            return {"Натуральный йогурт": 200, "Ягоды": 100, "Орехи": 20}
        if "хумус" in title:
            return {"Хумус": 120, "Хлебцы": 50, "Огурцы": 120}
        return {"Фрукты": 180, "Орехи": 25}
    if any(word in title for word in ("паста", "спагетти", "лазанья", "карбонара")):
        return {"Макароны": 110, "Куриное филе": 160, "Томаты": 160, "Сыр": 30}
    if "пицца" in title:
        return {"Тесто для пиццы": 180, "Томаты": 150, "Сыр": 90, "Куриное филе": 120, "Шампиньоны": 100}
    if any(word in title for word in ("картофель", "пюре", "драники", "запеканка")):
        return {"Картофель": 300, "Куриное филе": 170, "Овощи": 180}
    if any(word in title for word in ("рис", "плов", "ризотто", "паэлья")):
        return {"Рис": 110, "Куриное филе": 170, "Овощи": 200}
    if any(word in title for word in ("фасоль", "чечевиц", "фалафель", "тофу")):
        return {"Чечевица": 150, "Овощи": 220, "Томаты": 150, "Хлеб цельнозерновой": 70}
    if any(word in title for word in ("рыб", "морепродукт")):
        return {"Рыба": 180, "Крупа": 100, "Овощи": 200}
    return {"Куриное филе": 180, "Крупа": 100, "Овощи": 220}


def _extra_diet(name: str) -> str:
    title = name.casefold()
    if any(word in title for word in ("чечевиц", "фалафель", "тофу", "томатный суп", "соба с овощами")):
        return "vegan"
    if any(word in title for word in ("гриб", "овощ", "тыкв", "драники", "кускус")):
        return "vegetarian"
    return "none"


