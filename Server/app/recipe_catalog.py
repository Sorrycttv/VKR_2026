    recipe["side_dish"] = recipe.get("side_dish") or SIDE_DISHES.get(recipe["name"], "")
    recipe["batch_servings"] = recipe.get("batch_servings") or (3 if recipe["name"] in MAKE_AHEAD_RECIPES else 1)
    recipe["storage_days"] = recipe.get("storage_days") or (2 if recipe["name"] in MAKE_AHEAD_RECIPES else 0)
